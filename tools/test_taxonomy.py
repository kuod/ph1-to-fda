"""Tests for the sponsor -> parent mapping. Run: python3 tools/test_taxonomy.py

The mapping lives in data/sponsor_parents.json (with an as-of date). These tests pin the sponsors that were once
credited to the wrong parent, check the file is well formed, and fail when a sponsor maps to a parent that shares no
word with it unless data/sponsor_review.json (regenerated by tools/sponsor_report.py) lists it, so every new
acquisition-style mapping gets looked at.
"""
import json, os, re, sys, unittest
sys.path.insert(0, os.path.dirname(__file__))
import sponsor_report
from taxonomy import AS_OF, PARENTS, parent

D = os.path.join(os.path.dirname(__file__), "..", "data")
with open(os.path.join(D, "sponsor_parents.json")) as _f:
    SPEC = json.load(_f)


class KnownMisattributions(unittest.TestCase):
    CASES = [
        # (sponsor as openFDA writes it, expected parent)
        ("DECIPHERA PHARMS", "Deciphera"),             # 'RA PHARM' substring once credited these to UCB
        ("RA PHARMACEUTICALS INC", "UCB"),             # the company the pattern is meant to catch
        ("MARATHON PHARMACEUTICALS LLC", "Marathon"),  # was Takeda
        ("ARDELYX INC", "Ardelyx"),                    # was Kyowa Kirin
        ("XENCOR INC", "Xencor"),                      # was Johnson & Johnson
        ("AERIE PHARMS INC", "Alcon"),
        ("AGIOS PHARMS INC", "Agios"),
        ("FIVE PRIME THERAPEUTICS INC", "Amgen"),
        ("CELLTRION INC", "Celltrion"),
        ("ALCON LABS INC", "Alcon"),                   # not folded into Novartis
        ("ORGANON LLC", "Organon"),                    # not folded into Merck
        ("Lundbeck Seattle BioPharmaceuticals, Inc.", "Lundbeck"),  # not folded into Otsuka
        ("RENGENERON PHARMACEUTICALS, INC.", "Regeneron"),          # openFDA typo
        ("SAGE THERAP SUPERNUS", "Supernus"),
        ("MERCK KGAA", "Merck KGaA"),
        ("MERCK SHARP DOHME", "Merck & Co."),
        ("SEAGEN", "Pfizer"),
    ]

    def test_cases(self):
        for sponsor, want in self.CASES:
            with self.subTest(sponsor=sponsor):
                self.assertEqual(parent(sponsor), want)

    def test_blank(self):
        self.assertEqual(parent(""), "Unknown")
        self.assertEqual(parent(None), "Unknown")


class FileShape(unittest.TestCase):
    def test_as_of_is_a_date(self):
        self.assertRegex(SPEC["as_of"], r"^\d{4}-\d{2}-\d{2}$")
        self.assertEqual(AS_OF, SPEC["as_of"])

    def test_patterns_compile_and_are_not_empty(self):
        for r in SPEC["rules"]:
            self.assertTrue(r["parent"] and r["patterns"], r)
            for p in r["patterns"]:
                with self.subTest(pattern=p["re"]):
                    self.assertTrue(p["re"].strip())
                    self.assertIsNone(re.search(p["re"], ""), "pattern matches the empty string")

    def test_no_duplicate_patterns(self):
        seen = {}
        for r in SPEC["rules"]:
            for p in r["patterns"]:
                self.assertNotIn(p["re"], seen, f"{p['re']} listed under {seen.get(p['re'])} and {r['parent']}")
                seen[p["re"]] = r["parent"]

    def test_short_patterns_are_word_bounded(self):
        # a bare 4-letter substring is how RA PHARM matched Deciphera; short patterns need an anchor or \b
        allow = {"TEVA", "KAI PHARM", "ONYX", "MSD MERCK", "FIVE PRIME"}
        for r in SPEC["rules"]:
            for p in r["patterns"]:
                letters = re.sub(r"[^A-Z]", "", re.sub(r"\\[bB]", "", p["re"]))
                if len(letters) <= 4 and p["re"] not in allow:
                    with self.subTest(pattern=p["re"]):
                        self.assertRegex(p["re"], r"\\b|\^|\$")

    def test_removed_mappings_stay_removed(self):
        for r in SPEC["removed_wrong_mappings"]:
            if r["pattern"].isalpha():
                for rule in SPEC["rules"]:
                    self.assertNotIn(r["pattern"], [p["re"] for p in rule["patterns"]])

    def test_parents_list_matches_file(self):
        self.assertEqual([p for _, p in PARENTS], [r["parent"] for r in SPEC["rules"]])


class ReviewFileIsCurrent(unittest.TestCase):
    def test_every_no_token_mapping_is_in_the_review_file(self):
        listed = {(r["sponsor"], r["parent"]) for r in sponsor_report.load("sponsor_review.json")["mapped_no_shared_token"]}
        now = {(r["sponsor"], r["parent"]) for r in sponsor_report.build()["mapped_no_shared_token"]}
        self.assertEqual(now - listed, set(), "new sponsor->parent mapping(s) with no shared word: review them, then run tools/sponsor_report.py and commit data/sponsor_review.json")


if __name__ == "__main__":
    unittest.main()
